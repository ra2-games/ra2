import { frameCounterImage } from './frameCounterImage';
import { le32 } from '../../src/games/shared/bytes';

/** Synthetic compiler shapes at deliberately unrelated addresses; no executable files are required. */
export function adaptiveImage(game: 'ra2' | 'yr', base = 0x400000, shift = 0, temp: 'ecx' | 'edx' = 'ecx') {
  const f = frameCounterImage(game, base, shift);
  const pointer = base + 0x2200 + shift;
  const settingsOffset = game === 'ra2' ? 0x1108 : 0x14a0;
  const registers = game === 'ra2' ? [0x88, 0x0d, 0x90, 0x15] : [0x90, 0x15, 0x88, 0x0d];
  const prefix = [0xa1, ...le32(pointer), 0x68, ...le32(base + 0x3000)];
  for (const [i, offset] of [-28, -12, -4].entries()) {
    prefix.push(
      0x8b,
      registers[(i % 2) * 2]!,
      ...le32(settingsOffset + offset),
      0x89,
      registers[(i % 2) * 2 + 1]!,
      ...le32(f.session + 0x80 + i * 4),
    );
  }
  f.patch(f.sites.settings - prefix.length, prefix);
  const menu = base + 0x1500 + shift;
  const reg = game === 'ra2' ? 0xbd : 0xbe;
  const scratch = temp === 'ecx' ? 1 : 2;
  f.patch(menu - 9, [
    0xa1,
    ...le32(f.session - 48),
    0x3b,
    0xc3,
    0x75,
    7,
    reg,
    18,
    0,
    0,
    0,
    0xeb,
    13,
    0x33,
    temp === 'ecx' ? 0xc9 : 0xd2,
    0x83,
    0xf8,
    4,
    0x0f,
    0x94,
    0xc0 + scratch,
    0x83,
    0xc0 + scratch,
    16,
    0x8b,
    (game === 'ra2' ? 0xe8 : 0xf0) + scratch,
    0xa0,
    ...le32(f.frame - 1),
    0x84,
    0xc0,
  ]);
  const battle = base + 0x1600 + shift;
  const callback = base + 0x1700 + shift;
  const handler = base + 0x1800 + shift;
  const call = (site: number, at: number, target = handler) => [0xe8, ...le32(target - site - at - 5)];
  f.patch(battle, [
    0x8b,
    0x44,
    0x24,
    4,
    0x3d,
    0x17,
    6,
    0,
    0,
    0x74,
    0x22,
    0x3d,
    0xc0,
    5,
    0,
    0,
    0x74,
    0x1b,
    ...call(battle, 18),
    0x3c,
    1,
    0x74,
    0x12,
    0x32,
    0xc9,
    ...call(battle, 29),
    0x8b,
    0x44,
    0x24,
    4,
    0x3d,
    0x17,
    6,
    0,
    0,
    0x75,
    0xde,
  ]);
  f.patch(battle - 48, [0xba, ...le32(callback), 0xb9, 2, 1, 0, 0]);
  f.patch(callback + 0x3a, [
    0x81,
    0xfe,
    0x11,
    1,
    0,
    0,
    0x75,
    0x79,
    0x8b,
    0xc5,
    0x8b,
    0xd5,
    0xc1,
    0xe8,
    16,
    0x50,
    0x57,
    0x81,
    0xe2,
    0xff,
    0xff,
    0,
    0,
    0x8b,
    0xcb,
    ...call(callback + 0x3a, 25),
    0x5f,
    0x5e,
    0x5d,
    0xb8,
    1,
    0,
    0,
    0,
    0x5b,
    0xc2,
    16,
    0,
  ]);
  f.patch(handler, [
    0x81,
    0xec,
    ...le32(0x248),
    0x53,
    0x55,
    0x56,
    0x57,
    0x8b,
    0xe9,
    0x8b,
    game === 'ra2' ? 0xda : 0xf2,
  ]);
  const lanSites = [0x1900, 0x1940, 0x1980, 0x19c0].map((at) => base + at + shift);
  [
    [0xb9, 5, 0, 0, 0, 0x3b, 0xc6, 0x89, 0x0d, ...le32(f.fps - 4)],
    [
      0xb8,
      5,
      0,
      0,
      0,
      0x89,
      0x15,
      ...le32(f.speed),
      0x8b,
      0x15,
      ...le32(f.session - 28),
      0x3b,
      0xd6,
      0xa3,
      ...le32(f.fps - 4),
    ],
    [0xb8, 5, 0, 0, 0, 0x3b, 0xce, 0xa3, ...le32(f.fps - 4)],
    [0xb8, 5, 0, 0, 0, 0x3b, 0xcf, 0xa3, ...le32(f.fps - 4)],
  ].forEach((bytes, i) => f.patch(lanSites[i]!, bytes));
  const report = base + 0x1a40 + shift;
  const negotiate = base + 0x1b00 + shift;
  f.patch(report - 54, [
    0x8b,
    0x0d,
    ...le32(f.frame),
    0x8b,
    0x35,
    ...le32(pointer),
    0x8b,
    0x1d,
    ...le32(pointer),
    0x8b,
    0xd1,
    0x81,
    0xe2,
    0xff,
    0,
    0,
    0,
    0x3b,
    0xcf,
    0x89,
    0x34,
    0x95,
    ...le32(pointer),
    0xba,
    20,
    0,
    0,
    0,
    0x0f,
    0x84,
    ...le32(100),
    0x3b,
    0xdf,
    0x0f,
    0x85,
    ...le32(100),
    0xf6,
    0xc1,
    127,
    0x0f,
    0x85,
    ...le32(100),
    0x8b,
    0x45,
    0,
    0x8b,
    0xcd,
    0xff,
    0x50,
    0x30,
  ]);
  f.patch(negotiate, [0xa0, ...le32(f.frame), 0x84, 0xc0, 0x0f, 0x85, ...le32(100)]);
  const repair = base + 0x1c80 + shift;
  const repairOffset = 0x1348;
  const multiplier = base + 0x3040;
  const value = new Uint8Array(8);
  new DataView(value.buffer).setFloat64(0, 900, true);
  f.patch(multiplier, value);
  f.patch(repair, [
    0xa1,
    ...le32(pointer),
    0xdd,
    0x80,
    ...le32(repairOffset),
    0xdc,
    0x0d,
    ...le32(multiplier),
    ...call(repair, 17),
    0x8b,
    0xc8,
    0xa1,
    ...le32(f.frame),
    0x99,
    0xf7,
    0xf9,
    0x85,
    0xd2,
    0x74,
    6,
    0x5f,
    0x5e,
    0x32,
    0xc0,
    0x5b,
    0xc3,
  ]);
  return {
    ...f,
    pointer,
    repair,
    repairOffset,
    settingsOffset,
    menu,
    battle,
    callback,
    handler,
    lanSites,
    report,
    negotiate,
  };
}
