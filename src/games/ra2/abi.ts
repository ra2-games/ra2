export function ra2Win32ArgBytes(dll: string, name: string): number {
  const key = `${dll.toUpperCase()}!${name}`;
  const bytes = RA2_ABI[key];
  if (bytes === undefined) throw new Error(`未登记的 Red Alert 2 Win32 ABI: ${key}`);
  return bytes;
}
